def main():
    d = pd.read_csv(RESULTS / "ext_error_sample.csv")
    assert len(d) == len(TRANS) == 120, (len(d), len(TRANS))
    d["中文翻譯"] = TRANS
    d[["中文翻譯"]].rename_axis("編號").reset_index().to_csv(RESULTS / "ext_error_translation.csv", index=False,
                                                          encoding="utf-8-sig")
    wb = Workbook()
    head = Font(bold=True, color="FFFFFF")
    fill = PatternFill("solid", fgColor="3B6EA5")
    wrap = Alignment(wrap_text=True, vertical="top")

    ws = wb.active
    ws.title = "說明"
    lines = [
        "錯誤原因歸類：作者獨立歸類（盲測）",
        "",
        "1. 這 120 則評論，都是 BERTimbau Large 微調「最有把握卻判錯」的評論：1–2 星被判成正面（假正評），或 4–5 星被判成負面（假負評）。",
        "2. 請到「歸類」工作表，替每一則選一個「主要原因」（1–6），填在 F 欄。G 欄會自動顯示類別名稱，H 欄可以寫備註。",
        "3. 請只看原文、星等與翻譯自己判斷。這個檔案沒有 AI 的歸類與理由，填完之前也請不要去看 results/ext_error_sample.csv 或報告附錄表 A-7。",
        "4. 中文翻譯由 AI 助理直譯，以原文為準。lannister、baratheon 是 Olist 匿名化後的店名／發卡機構名稱。",
        "5. 填完存檔後，執行 python src/ext_error_kappa.py，就會計算你和 AI 歸類的一致性（Cohen's kappa）。",
        "",
        "類別定義：",
    ] + [f"{k} {NAMES[k]}：{v}" for k, v in DEFS.items()]
    for i, t in enumerate(lines, 1):
        ws.cell(i, 1, t).alignment = Alignment(wrap_text=True)
    ws["A1"].font = Font(bold=True, size=14)
    ws.column_dimensions["A"].width = 120

    ws = wb.create_sheet("歸類")
    cols = ["編號", "星等", "模型判斷", "原文（葡萄牙文）", "中文翻譯", "你的歸類（1–6）", "類別名稱", "備註"]
    widths = [6, 6, 10, 60, 60, 14, 16, 30]
    for j, (c, w) in enumerate(zip(cols, widths), 1):
        cell = ws.cell(1, j, c)
        cell.font, cell.fill, cell.alignment = head, fill, Alignment(horizontal="center", vertical="center", wrap_text=True)
        ws.column_dimensions[cell.column_letter].width = w
    names = ",".join(f'"{NAMES[k]}"' for k in sorted(NAMES))
    for i, r in d.iterrows():
        row = i + 2
        vals = [i, int(r.rating), "判成正面" if r.rating <= 2 else "判成負面", str(r.review_text).strip(), r.中文翻譯]
        for j, v in enumerate(vals, 1):
            ws.cell(row, j, v).alignment = wrap
        ws.cell(row, 6).alignment = Alignment(horizontal="center", vertical="top")
        ws.cell(row, 7, f'=IF(F{row}="","",CHOOSE(F{row},{names}))').alignment = wrap
    dv = DataValidation(type="whole", operator="between", formula1="1", formula2="6", allow_blank=True,
                        showErrorMessage=True, errorTitle="歸類", error="請填 1–6 的整數")
    dv.add(f"F2:F{len(d) + 1}")
    ws.add_data_validation(dv)
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:H{len(d) + 1}"
    wb.active = 1
    wb.save(OUT)
    print(f"已產生 {OUT}（{len(d)} 則）與 results/ext_error_translation.csv")


if __name__ == "__main__":
    main()
