def main():
    path = RESULTS / "ext_error_sample.csv"
    d = pd.read_csv(path)
    assert len(d) == len(CODE) == 120, "樣本數和歸類數不一致"
    d["人工歸類"] = [NAMES[CODE[i][0]] for i in range(len(d))]
    d["歸類理由"] = [CODE[i][1] for i in range(len(d))]
    d.to_csv(path, index=False, encoding="utf-8-sig")

    d["類型"] = d.錯誤類型.str[:3]
    tab = pd.crosstab(d.人工歸類, d.類型).reindex(list(NAMES.values())).fillna(0).astype(int)
    tab["合計"] = tab.sum(axis=1)
    tab["占比"] = (tab.合計 / len(d)).round(3)
    tab["其他3個模型也錯的平均數"] = d.groupby("人工歸類").其他模型也錯的數量.mean().round(2)
    tab = tab.reset_index()
    tab.to_csv(RESULTS / "ext_error_coding.csv", index=False)
    log_text("\n錯誤原因歸類（120 則）：\n" + tab.to_string(index=False))
    label_noise = (d.人工歸類 == NAMES[1]).mean()
    model_wrong = (d.人工歸類 == NAMES[5]).mean()
    log(f"評分與文字矛盾（標籤雜訊）占 {label_noise:.0%}；模型真的判錯只占 {model_wrong:.0%}")

    plt.rcParams["font.family"] = ["Microsoft JhengHei", "sans-serif"]
    plt.rcParams["axes.unicode_minus"] = False
    t = tab.set_index("人工歸類").iloc[::-1]
    fig, ax = plt.subplots(figsize=(8.5, 3.8))
    y = range(len(t))
    ax.barh(y, t["假正評"], color="#2a78d6", height=0.62, label="假正評（1–2 星被判成正面）")
    ax.barh(y, t["假負評"], left=t["假正評"], color="#eb6834", height=0.62, label="假負評（4–5 星被判成負面）",
            edgecolor="white", linewidth=2)
    for i, (n, p) in enumerate(zip(t.合計, t.占比)):
        ax.text(n + 1, i, f"{n} 則（{p:.0%}）", va="center", fontsize=9, color="#0b0b0b")
    ax.set_yticks(list(y), t.index)
    ax.set_xlim(0, t.合計.max() * 1.25)
    ax.set_xlabel("則數（共 120 則：模型最有把握卻判錯的評論）")
    for s in ["top", "right"]:
        ax.spines[s].set_visible(False)
    ax.grid(axis="x", color="#e1e0d9", lw=0.6)
    ax.set_axisbelow(True)
    ax.legend(loc="lower right", frameon=False, fontsize=9)
    fig.tight_layout()
    fig.savefig(FIGURES / "rq1_error_coding.png", dpi=200, bbox_inches="tight")
    plt.close(fig)
    log(f"結果已存到 results/ext_error_sample.csv、results/ext_error_coding.csv、figures/rq1_error_coding.png；記錄檔 {LOG_PATH}")


if __name__ == "__main__":
    main()
